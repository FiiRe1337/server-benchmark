#!/usr/bin/env python3
"""Build step (build-gui.yml): write sbgui/_build_info.py with GUI version, commit and the SHA-256 + version of the
core binary that gets embedded, and stage the binary as core-bin/sbench.exe for sbench-gui.spec.

  python tools/gen_build_info.py --core <path\\to\\sbench.exe> [--version X] [--commit SHA] [--core-version V] [--run-core]

Version resolution (same order as build-windows.yml): --version, tag v* (GITHUB_REF), git describe --tags --match v[0-9]*,
0.1.0-ci.<GITHUB_RUN_NUMBER>+<short sha> (0.1.0-dev+<sha> outside CI).
--run-core executes `<core> version --json` (Windows runner) and requires its sha256 to equal the file hash."""
import argparse, datetime as dt, hashlib, json, os, shutil, subprocess, sys

GUI = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _git(*args):
    try:
        cp = subprocess.run(["git", *args], capture_output=True, text=True, cwd=GUI, timeout=20)
        return cp.stdout.strip() if cp.returncode == 0 else ""
    except (OSError, subprocess.TimeoutExpired):
        return ""


def resolve_version(explicit=None, env=None, describe=None, short_sha=None):
    """explicit -> tag (refs/tags/v1.2.3 -> 1.2.3) -> git describe (v-prefix stripped) -> 0.1.0-ci.<run>+<sha>."""
    env = os.environ if env is None else env
    if explicit and explicit.strip():
        return explicit.strip()
    ref = env.get("GITHUB_REF", "")
    if ref.startswith("refs/tags/v"):
        return ref[len("refs/tags/v"):]
    d = _git("describe", "--tags", "--match", "v[0-9]*") if describe is None else describe
    if d:
        return d[1:] if d.startswith("v") else d
    sha = (_git("rev-parse", "--short=7", "HEAD") if short_sha is None else short_sha) or "unknown"
    run = env.get("GITHUB_RUN_NUMBER")
    return f"0.1.0-ci.{run}+{sha}" if run else f"0.1.0-dev+{sha}"


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def render(version, commit, core_sha, core_version, built_utc):
    return ("# generated by tools/gen_build_info.py -- do not edit, not in git\n"
            f"VERSION = {version!r}\nCOMMIT = {commit!r}\nCORE_SHA256 = {core_sha!r}\n"
            f"CORE_VERSION = {core_version!r}\nBUILT_UTC = {built_utc!r}\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--core", required=True); ap.add_argument("--version", default="")
    ap.add_argument("--commit", default=""); ap.add_argument("--core-version", default="")
    ap.add_argument("--run-core", action="store_true")
    ap.add_argument("--out", default=os.path.join(GUI, "sbgui", "_build_info.py"))
    ap.add_argument("--stage", default=os.path.join(GUI, "core-bin", "sbench.exe"))
    a = ap.parse_args(argv)
    version = resolve_version(a.version)
    commit = a.commit or os.environ.get("GITHUB_SHA") or _git("rev-parse", "HEAD") or "unknown"
    sha = sha256_file(a.core)
    core_version = a.core_version or version
    if a.run_core:
        v = json.loads(subprocess.run([a.core, "version", "--json"], capture_output=True, text=True, check=True, timeout=60).stdout)
        if v.get("sha256") != sha:
            sys.exit(f"sbench version --json meldet sha256 {v.get('sha256')}, Datei hat {sha}")
        core_version = v.get("version") or core_version
    if os.path.abspath(a.core) != os.path.abspath(a.stage):
        os.makedirs(os.path.dirname(a.stage), exist_ok=True); shutil.copyfile(a.core, a.stage)
    if sha256_file(a.stage) != sha:
        sys.exit("Staging-Kopie des Kerns weicht ab")
    built = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(version, commit, sha, core_version, built))
    info = {"version": version, "commit": commit, "core_sha256": sha, "core_version": core_version, "built_utc": built}
    print(json.dumps(info, indent=1))
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as f:
            for k, v in info.items():
                f.write(f"{k}={v}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
